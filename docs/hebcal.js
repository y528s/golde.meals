/* =============================================================================
   The Jewish calendar, as far as a meal train needs it
   -----------------------------------------------------------------------------
   Three things change what a meal train should say:

     the parsha    — "Friday, Parshas Vayeira" is how people in this community
                     actually name a week, and getting it right is the clearest
                     signal that whoever built this knows who it is for
     yom tov       — nobody cooks on a chag, and candle-lighting moves
     fast days     — a fast means no dinner at all, and then a meal that
                     matters more than usual when it ends

   ---------------------------------------------------------------------------
   A WARNING, AND THE REASON THIS IS A TABLE RATHER THAN A CALCULATION
   ---------------------------------------------------------------------------
   The Hebrew calendar is genuinely intricate: leap years, the four dechiyot
   that shift Rosh Hashanah, six possible year-lengths, and a parsha cycle that
   doubles and splits differently in Israel and the diaspora depending on where
   a festival falls. It is entirely possible to compute — but computing it
   badly, or from memory, produces something that looks authoritative and is
   quietly wrong.

   Being wrong here is worse than being silent. Telling a community that this
   Shabbos is Parshas Vayishlach when it is Vayeitzei does not read as a minor
   bug; it reads as an outsider guessing.

   So: this is a verified table, and anything outside it returns null and the
   app simply says nothing. Silence is always correct.

     npm run calendar        regenerate from hebcal.com

   The dates below MUST be checked against hebcal.com before a real train runs
   in any week they cover. They are marked with the diaspora schedule.
   ============================================================================= */

(function () {
  "use strict";

  /* --- verified window ------------------------------------------------------
     Generated by tools/fetch-calendar.js, diaspora schedule.
     VERIFY BEFORE USE — see the warning above. */
  /* An impossible window until calendar-data.js says otherwise, so every
     question answers null and she stays quiet. */
  var VERIFIED_FROM = "9999-01-01";
  var VERIFIED_TO   = "0000-01-01";

  /* iso -> { parsha, candles } for Fridays; iso -> { yomtov | fast } elsewhere */
  var DAYS = {};

  /* --- the questions the app asks ------------------------------------------ */

  function known(iso) {
    return iso >= VERIFIED_FROM && iso <= VERIFIED_TO;
  }

  /* The parsha read on the Shabbos that a given Friday leads into. Null when
     we have not verified that week — the caller must cope with null. */
  function parshaFor(iso) {
    if (!known(iso)) return null;
    var d = DAYS[iso];
    return (d && d.parsha) || null;
  }

  function candleLighting(iso) {
    if (!known(iso)) return null;
    var d = DAYS[iso];
    return (d && d.candles) || null;
  }

  /* A day nobody should be asked to cook on, or to eat on. */
  function noCookingOn(iso) {
    if (!known(iso)) return null;
    var d = DAYS[iso];
    if (!d) return null;
    if (d.yomtov) return { kind: "yomtov", name: d.yomtov };
    if (d.fast) return { kind: "fast", name: d.fast };
    return null;
  }

  /* What Golde says about it, if anything. Silence when unsure. */
  function noteFor(iso) {
    var stop = noCookingOn(iso);
    if (stop && stop.kind === "yomtov") {
      return "It's " + stop.name + ". Nobody's cooking for anybody — I've left it off.";
    }
    if (stop && stop.kind === "fast") {
      return "It's " + stop.name + ", so there's no dinner. Something for after the fast is " +
             "a kindness, though — people come home hollow.";
    }
    var p = parshaFor(iso);
    var c = candleLighting(iso);
    if (p && c) return "Parshas " + p + ". Candles at " + c + ".";
    if (c) return "Candles at " + c + ".";
    return null;
  }

  window.goldeCalendar = {
    verifiedFrom: VERIFIED_FROM,
    verifiedTo: VERIFIED_TO,
    isVerified: known,
    parshaFor: parshaFor,
    candleLighting: candleLighting,
    noCookingOn: noCookingOn,
    noteFor: noteFor,
    /* Populated by the generated file, if one has been built. */
    load: function (table, from, to) {
      DAYS = table || {};
      VERIFIED_FROM = from;
      VERIFIED_TO = to;
      if (window.goldeCalendarReady) window.goldeCalendarReady();
    }
  };
})();
